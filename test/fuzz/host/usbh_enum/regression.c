#include <stddef.h>
#include <stdint.h>

// Keep the input format and generation ranges synchronized with fuzz.c.
#define INPUT_INTERFACES_OFFSET       0u
#define INPUT_CONFIG_VALUE_OFFSET     1u
#define INPUT_DECISION_OFFSET         2u
#define TEST_INPUT_SIZE               3u

#define TEST_INTERFACE_VARIANTS       4u
#define TEST_SECOND_CONFIG_VALUE_MIN  3u
#define TEST_CONFIG_VALUE_VARIANTS \
  (UINT8_MAX - TEST_SECOND_CONFIG_VALUE_MIN + 1u)

#define TEST_ACCEPT_FIRST             0u
#define TEST_ACCEPT_SECOND            1u
#define TEST_REJECT_ALL               2u
#define TEST_DECISION_COUNT           (TEST_REJECT_ALL + 1u)

extern int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size);

int main(void) {
  // Explicitly exercise the default regression:
  // reject index 0, accept index 1 with a different descriptor length, then
  // require SET_CONFIGURATION(7).
  LLVMFuzzerTestOneInput(NULL, 0);

  // Exhaust every distinct fixture generated by the three input bytes:
  //   4 interface-count choices
  //   253 configuration values (3 through 255)
  //   3 application decisions
  //
  // This runs 3,036 combinations plus the default case above.
  for (unsigned interfaces = 0; interfaces < TEST_INTERFACE_VARIANTS; interfaces++) {
    for (unsigned value = 0; value < TEST_CONFIG_VALUE_VARIANTS; value++) {
      for (unsigned decision = TEST_ACCEPT_FIRST; decision < TEST_DECISION_COUNT; decision++) {
        uint8_t input[TEST_INPUT_SIZE] = {0};

        // These are encoded inputs. The harness adds the minimum interface
        // count and minimum configuration value when constructing descriptors.
        input[INPUT_INTERFACES_OFFSET] = (uint8_t) interfaces;
        input[INPUT_CONFIG_VALUE_OFFSET] = (uint8_t) value;
        input[INPUT_DECISION_OFFSET] = (uint8_t) decision;

        LLVMFuzzerTestOneInput(input, sizeof(input));
      }
    }
  }

  // Any failed harness check aborts the process before reaching this return.
  return 0;
}
